import {test,before,after} from 'node:test';
import assert from 'node:assert/strict';
import {createServer} from 'node:http';
import {readFile,mkdir} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {extname,join,normalize} from 'node:path';
import {fileURLToPath} from 'node:url';
const {chromium}=createRequire(import.meta.url)('playwright');
const root=fileURLToPath(new URL('../../',import.meta.url));
let server,browser,base;
before(async()=>{server=createServer(async(req,res)=>{const p=normalize(decodeURIComponent(new URL(req.url,'http://x').pathname)).replace(/^[/\\]+/,'')||'index.html';try{const b=await readFile(join(root,p));res.writeHead(200,{'content-type':({'.js':'text/javascript','.html':'text/html','.css':'text/css','.json':'application/json','.webp':'image/webp','.png':'image/png'})[extname(p)]||'application/octet-stream'});res.end(b)}catch{res.writeHead(404);res.end()}});await new Promise(r=>server.listen(0,'127.0.0.1',r));base='http://127.0.0.1:'+server.address().port+'/';browser=await chromium.launch();await mkdir(join(root,'tests/.downloads'),{recursive:true});});
after(async()=>{await browser?.close();server?.close();});
for(const id of ['cancao-exilio-completa','citologia-completa'])test(id+': anexar, remover, desfazer, salvar, exportar e imprimir',{timeout:150000},async()=>{
 const a=JSON.parse(await readFile(join(root,'casos',id+'.json'),'utf8'));
 const ctx=await browser.newContext({viewport:{width:390,height:844},serviceWorkers:'block'}),p=await ctx.newPage();
 const errors=[];p.on('pageerror',e=>errors.push(e.message));
 try{
  await p.goto(base+'planejar.html?ensaio=1&demonstracao=1');
  await p.locator('#modelosProntos li').filter({hasText:a.titulo}).getByRole('button',{name:'Abrir',exact:true}).click();
  await p.getByRole('button',{name:'5 Observar e descrever a imagem',exact:true}).click();
  assert.ok(await p.getByRole('button',{name:'Remover imagem',exact:true}).isVisible());
  await p.getByRole('button',{name:'Remover imagem',exact:true}).click();
  assert.ok(await p.getByText('Nenhuma imagem anexada nesta etapa.',{exact:false}).isVisible());
  const image=a.etapas.find(e=>e.config.imagem).config.imagem;
  await p.locator('input[type=file]').setInputFiles({name:'imagem-do-professor.webp',mimeType:'image/webp',buffer:Buffer.from(image.dados.split(',')[1],'base64')});
  await p.getByText('Imagem anexada: imagem-do-professor.webp',{exact:true}).waitFor();
  assert.ok(await p.locator('.anexo-docente img').evaluate(im=>im.complete&&im.naturalWidth>0));
  await p.getByRole('button',{name:'Remover imagem',exact:true}).click();await p.getByText('Guardar e exportar',{exact:true}).click();await p.getByRole('button',{name:'Desfazer',exact:true}).click();
  assert.ok(await p.getByText('Imagem anexada: imagem-do-professor.webp',{exact:true}).isVisible());
  assert.ok(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Sem transbordamento em tela de celular');
  await p.getByText('Guardar e exportar',{exact:true}).click();await p.getByRole('button',{name:'Salvar na biblioteca',exact:true}).click();
  await p.getByRole('dialog').getByRole('button',{name:'Salvar',exact:true}).click();await p.getByRole('status').filter({hasText:'Salvo na sua biblioteca'}).waitFor();
  await p.reload();await p.getByRole('button',{name:'5 Observar e descrever a imagem',exact:true}).click();
  assert.ok(await p.getByText('Imagem anexada: imagem-do-professor.webp',{exact:true}).isVisible());
  await p.getByText('Guardar e exportar',{exact:true}).click();
  const [json]=await Promise.all([p.waitForEvent('download'),p.getByRole('button',{name:'Baixar arquivo da atividade',exact:true}).click()]);
  const saved=JSON.parse(await readFile(await json.path(),'utf8'));assert.equal(saved.etapas.length,22);assert.equal(saved.etapas.find(e=>e.id==='e5').config.imagem.nome,'imagem-do-professor.webp');
  await p.getByText('Guardar e exportar',{exact:true}).click();
  const [xlsx]=await Promise.all([p.waitForEvent('download'),p.getByRole('button',{name:'Baixar planilha',exact:true}).click()]);
  const sheet=await xlsx.path();assert.ok((await readFile(sheet)).length>20000);
  await p.getByText('Guardar e exportar',{exact:true}).click();
  const [paper]=await Promise.all([ctx.waitForEvent('page'),p.getByRole('button',{name:'Imprimir',exact:true}).click()]);
  await paper.waitForLoadState();assert.match(await paper.locator('body').innerText(),/MATERIAL DE QUEM CONDUZ/);
  for(const e of a.etapas)assert.ok((await paper.locator('body').innerText()).includes(e.titulo),'Impressão contém '+e.titulo);
  assert.equal(await paper.locator('img').evaluateAll(imgs=>imgs.filter(im=>!im.complete||!im.naturalWidth).length),0,'Imagens carregadas no material impresso');
  await paper.emulateMedia({media:'print'});await paper.pdf({path:join(root,'tests/.downloads',id+'.pdf'),format:'A4',printBackground:true});
  await paper.close();
  await p.getByRole('button',{name:'Ajustar',exact:true}).first().click();
  await p.getByRole('link',{name:'Criar',exact:true}).click();
  await p.locator('#arqImport').setInputFiles(sheet);await p.getByRole('button',{name:'5 Observar e descrever a imagem',exact:true}).click();
  assert.ok(await p.getByText('Imagem anexada: imagem-do-professor.webp',{exact:true}).isVisible());
  await p.screenshot({path:join(root,'tests/.downloads',id+'-anexo.png'),fullPage:true});
  assert.deepEqual(errors,[]);
 }finally{await ctx.close();}
});
